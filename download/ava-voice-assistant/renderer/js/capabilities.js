  /* جستجو: بهترین تطبیق کلیدواژه‌ها — خروجی: {cap, key} یا null */
  function search(text) {
    const n = normFa(text);
    if (!n || n.length < 4) return null;
    let best = null, bestScore = 0;
    for (const cap of CAPS) {
      for (const re of cap.k) {
        const m = n.match(re);
        if (m) {
          const score = m[0].length;
          if (score > bestScore) { bestScore = score; best = { cap, key: m[0] }; }
        }
      }
    }
    return bestScore >= 4 ? best : null;
  }

